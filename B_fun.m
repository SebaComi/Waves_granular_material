function B = B_fun(W,a1_vec,a2_vec,a3_vec,rho,u,v,F11_fun,F12_fun,F21_fun,F22_fun,DATA)
    % See my Matematica code: Hyperbolicity_Grains_F_no_beta.nb
    B = zeros(size(W,1),size(W,1),size(W,2),size(W,3));

    [u1,u2,~,~,F11,F12,F21,F22,a1,a2,b1,b2,c1,c2,d1,d2,e1,e2,f1,f2,~,~,~,AA,BB,CC,DD,EE,FF] = estrai(W,a1_vec,a2_vec,a3_vec,rho,u,v,F11_fun,F12_fun,F21_fun,F22_fun,DATA);

b0 = sqrt( b1.^2 +  b2.^2);
d0 = sqrt( d1.^2 +  d2.^2);
f0 = sqrt( f1.^2 +  f2.^2);

b0_2 = b0.^2;   b1_2 = b1.^2;   b2_2 = b2.^2;
d0_2 = d0.^2;   d1_2 = d1.^2;   d2_2 = d2.^2;
f0_2 = f0.^2;   f1_2 = f1.^2;   f2_2 = f2.^2;
b1_3 = b1.^3;   b2_3 = b2.^3;
d1_3 = d1.^3;   d2_3 = d2.^3;
f1_3 = f1.^3;   f2_3 = f2.^3;


% B(1,1,:,:) = 0;
 % B(1,2,:,:) = 0;
 B(1,3,:,:) = 1;
 % B(1,4,:,:) = 0;
 % B(1,5,:,:) = 0;
 % B(1,6,:,:) = 0;
 % B(1,7,:,:) = 0;
 B(2,1,:,:) = AA.*b1.*b2+CC.*d1.*d2+EE.*f1.*f2-u1.*u2;
 B(2,2,:,:) = u2;
 B(2,3,:,:) = u1;
 B(2,4,:,:) = a1./b0_2.*b2.*(-AA.*b1_2+(b0_2-b1_2).*BB)+c1./d0_2.*d2.*(-CC.*d1_2+d0_2.*DD-d1_2.*DD)+e1./f0_2.*f2.*(-EE.*f1_2+f0_2.*FF-f1_2.*FF);
 B(2,5,:,:) = a2./b0_2.*b2.*(-AA.*b1_2+(b0_2-b1_2).*BB)+c2./d0_2.*d2.*(-CC.*d1_2+d0_2.*DD-d1_2.*DD)+e2./f0_2.*f2.*(-EE.*f1_2+f0_2.*FF-f1_2.*FF);
 B(2,6,:,:) = a1./b0_2.*(AA.*(-b0_2.*b1+b1_3)+b1_3.*BB)+c1./d0_2.*(-CC.*d0_2.*d1+CC.*d1_3+d1_3.*DD)+e1./f0_2.*f1.*(-EE.*f0_2+EE.*f1_2+f1_2.*FF);
 B(2,7,:,:) = a2./b0_2.*(AA.*(-b0_2.*b1+b1_3)+b1_3.*BB)+c2./d0_2.*(-CC.*d0_2.*d1+CC.*d1_3+d1_3.*DD)+e2./f0_2.*f1.*(-EE.*f0_2+EE.*f1_2+f1_2.*FF);
 B(3,1,:,:) = AA.*(b0_2-b1_2)+CC.*(d0_2-d1_2)+EE.*f0_2-EE.*f1_2-u2.^2;
 % B(3,2,:,:) = 0;
 B(3,3,:,:) = 2.*u2;
 B(3,4,:,:) = a1./b0_2.*b1.*(-b0_2+b1_2).*(AA+BB)+c1./d0_2.*d1.*(-d0_2+d1_2).*(CC+DD)+e1./f0_2.*f1.*(-f0_2+f1_2).*(EE+FF);
 B(3,5,:,:) = a2./b0_2.*b1.*(-b0_2+b1_2).*(AA+BB)+c2./d0_2.*d1.*(-d0_2+d1_2).*(CC+DD)+e2./f0_2.*f1.*(-f0_2+f1_2).*(EE+FF);
 B(3,6,:,:) = a1./b0_2.*b2.*(AA.*(-b0_2+b1_2)+(b0_2+b1_2).*BB)+c1./d0_2.*d2.*(CC.*(-d0_2+d1_2)+(d0_2+d1_2).*DD)+e1./f0_2.*f2.*(EE.*(-f0_2+f1_2)+(f0_2+f1_2).*FF);
 B(3,7,:,:) = a2./b0_2.*b2.*(AA.*(-b0_2+b1_2)+(b0_2+b1_2).*BB)+c2./d0_2.*d2.*(CC.*(-d0_2+d1_2)+(d0_2+d1_2).*DD)+e2./f0_2.*f2.*(EE.*(-f0_2+f1_2)+(f0_2+f1_2).*FF);
 B(4,1,:,:) = F21.*u1-F11.*u2;
 B(4,2,:,:) = -F21;
 B(4,3,:,:) = F11;
 B(4,4,:,:) = u2;
 % B(4,5,:,:) = 0;
 % B(4,6,:,:) = 0;
 % B(4,7,:,:) = 0;
 B(5,1,:,:) = F22.*u1-F12.*u2;
 B(5,2,:,:) = -F22;
 B(5,3,:,:) = F12;
 % B(5,4,:,:) = 0;
 B(5,5,:,:) = u2;
 % B(5,6,:,:) = 0;
 % B(5,7,:,:) = 0;
 % B(6,1,:,:) = 0;
 % B(6,2,:,:) = 0;
 % B(6,3,:,:) = 0;
 % B(6,4,:,:) = 0;
 % B(6,5,:,:) = 0;
 B(6,6,:,:) = u2;
 % B(6,7,:,:) = 0;
 % B(7,1,:,:) = 0;
 % B(7,2,:,:) = 0;
 % B(7,3,:,:) = 0;
 % B(7,4,:,:) = 0;
 % B(7,5,:,:) = 0;
 % B(7,6,:,:) = 0;
 B(7,7,:,:) = u2;

    if true % Questo se voglio la matrice dopo aver usato il Piola's constraint
        B(4,6,:,:) = -u1;
        B(5,7,:,:) = -u1;
        B(6,6,:,:) = 0;
        B(7,7,:,:) = 0;
    end
end